#!/usr/bin/env bash
# F14-03: tests/27's 'all rows are preserved' after untransmute is a cardinality check (count(*) = 100). The
# fixture's rows are named ('b1' .. 'b100', one a minute back), so identity is available, but the assertion
# accepts any 100 rows: a reversal that lost rows and resurrected or duplicated others to the same count passes.
# The assertion is read from $TREE, not pasted, and evaluated over a table holding 100 rows, none of them the
# fixture's.
set -u
F="$TREE/tests/27_untransmute_test.sql"
n=$(grep -n "'all rows are preserved'" "$F" | head -1 | cut -d: -f1)
if [ -z "$n" ]; then echo "not ok - GUARD: the assertion is not in tests/27 (the defect is absent or moved)"; exit 0; fi
start=$(awk -v n="$n" 'NR<=n && /^select is\(/ {s=NR} END{print s}' "$F")
stmt=$(sed -n "${start},${n}p" "$F")
out=$($PSQL -tA <<SQL 2>&1
create extension if not exists pgtap;
create table public.rt (id bigint generated by default as identity, created_at timestamptz not null default now(),
                        body text, primary key (created_at, id));
-- 100 rows, none of them a row the fixture wrote (its bodies are b1 .. b100)
insert into public.rt (created_at, body) select now() - (g || ' days')::interval, 'lost-' || g from generate_series(1, 100) g;
select plan(2);
select ok(not exists (select 1 from public.rt where body ~ '^b[0-9]+$') and (select count(*) = 100 from public.rt),
  'LIVENESS: rt holds 100 rows and none of the fixture''s rows b1 .. b100');
$stmt
select * from finish();
SQL
)
echo "$out" | grep -E "^(not )?ok" | sed 's/^/# tests\/27 over a table of none of its rows: /'
if ! echo "$out" | grep -q "^ok 1 - LIVENESS: rt holds 100 rows"; then
  echo "not ok - LIVENESS: the substituted-rows state was not reached"; exit 1
fi
echo "ok - LIVENESS: the substituted-rows state was reached"
if echo "$out" | grep -q "^ok 2 - all rows are preserved"; then
  echo "not ok - tests/27 certifies 'all rows are preserved' over a table holding none of the rows its fixture wrote"
  exit 1
fi
echo "ok - tests/27's assertion refuses a table that lost its rows"
