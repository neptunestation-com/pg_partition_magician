-- P1-01: _snapshot_wait's floor-holder query looks for the holder in THIS database only (a.datid = v_db), so a
-- transaction open in ANOTHER database, the very case #1263 is about and the PR body says the clause covers
-- ("the holder can be a session of any database"), is never named: the refusal falls back to the old message
-- that calls the held-back local pid a reader that "would find the regrained range empty", and maintain's
-- skip_regrain row (which keeps the message through the holder clause) carries no holder either.
--
-- Shape of tests/333 part A, reduced: X opens a transaction in <db>_x before any copy; the copies run one
-- regrain_step per transaction to the swap's doorstep; B, a READ COMMITTED session of this database, runs a
-- statement begun after the copies, whose backend_xmin X holds at X's xid; the swap under a 300 ms budget
-- refuses. Defect check: the refusal names X's database, pid and xid. Fails on the review tree (the message
-- has no holder clause); passes once the holder is looked for in any database.
-- Asymmetric fixture: the multiples of 26 to 494 and frontier 2600; the read-back after names the ids.
create extension if not exists pgtap;
create extension if not exists dblink;
set client_min_messages = warning;
select plan(9);

create temp table p1_state (k text primary key, v text);
select dblink_exec('dbname=' || current_database() || ' user=postgres',
                   format('create database %I', current_database() || '_x'));

create table public.p1a (id bigint generated by default as identity primary key, payload text);
insert into public.p1a (id, payload) select g, 'a' || g from generate_series(26, 494, 26) g;
call pgpm.transmute('public.p1a', 'id', 100, p_paused => false);                   -- monolith [0, 500)
insert into public.p1a (id, payload) values (2600, 'frontier');                     -- freezes the monolith
insert into p1_state select 'src', child_name from pgpm.part
 where parent_table = 'public.p1a'::regclass and attached and lo = '0';

-- X: a transaction in the other database, its xid taken before any copy
select dblink_connect('x_p1', 'dbname=' || current_database() || '_x user=postgres');
select dblink_exec('x_p1', 'begin');
insert into p1_state select 'xxid', x from dblink('x_p1', 'select pg_current_xact_id()::text') as t(x text);
insert into p1_state select 'xpid', p::text from dblink('x_p1', 'select pg_backend_pid()') as t(p int);

-- the copies, one regrain_step per transaction, to the swap's doorstep
do $$
begin
  for i in 1..40 loop
    exit when (select regrain_cursor from pgpm.config where parent_table = 'public.p1a'::regclass) = '500';
    perform pgpm.regrain_step('public.p1a', (select v from p1_state where k = 'src'), '100');
    commit;
  end loop;
end $$;
select is((select regrain_cursor from pgpm.config where parent_table = 'public.p1a'::regclass), '500',
  'LIVENESS: every sub-range is copied and the run is at the swap');
select ok((select (select v from p1_state where k = 'xxid')::xid8 < c.regrain_written_xid
             from pgpm.config c where c.parent_table = 'public.p1a'::regclass),
  'LIVENESS: the other database''s transaction X took its xid before the copies'' last write, and is still open');

-- B: a READ COMMITTED session of this database, its statement begun after the copies
select dblink_connect('b_p1', 'dbname=' || current_database() || ' user=postgres');
insert into p1_state select 'bpid', p::text from dblink('b_p1', 'select pg_backend_pid()') as t(p int);
select dblink_send_query('b_p1', 'select pg_sleep(4)');
do $$
begin
  for i in 1..500 loop
    perform pg_stat_clear_snapshot();
    exit when exists (select 1 from pg_stat_activity
                       where pid = (select v::int from p1_state where k = 'bpid')
                         and state = 'active' and wait_event = 'PgSleep' and backend_xmin is not null);
    perform pg_sleep(0.01);
  end loop;
end $$;
select ok((select a.query_start > l.at
             from pg_stat_activity a,
                  (select max(at) as at from pgpm.log where parent_table = 'public.p1a'::regclass and action = 'regrain_copy') l
            where a.pid = (select v::int from p1_state where k = 'bpid') and a.state = 'active'),
  'LIVENESS: B is running a statement that began after the last copy was logged');
select is((select a.backend_xmin::text from pg_stat_activity a where a.pid = (select v::int from p1_state where k = 'bpid')),
  (select v from p1_state where k = 'xxid'),
  'LIVENESS: and B''s backend_xmin is X''s xid: the other database''s transaction holds its snapshot back');

set lock_timeout = '300ms';
select throws_like(
  format($$ select pgpm.regrain_step('public.p1a', %L, '100') $$, (select v from p1_state where k = 'src')),
  'pg_partition_magician: regrain swap deferred: 1 snapshot(s) older than the copies still open (oldest: pid '
    || (select v from p1_state where k = 'bpid')
    || ', open %); a transaction older than the copies is still running in database '
    || current_database() || '_x (pid ' || (select v from p1_state where k = 'xpid')
    || ', xid ' || (select v from p1_state where k = 'xxid') || ', open %',
  'the refusal names the transaction holding the snapshot back: its database (the other one), pid and xid');
reset lock_timeout;
select is((select count(*) from pgpm.log where parent_table = 'public.p1a'::regclass and action = 'regrain'), 0::bigint,
  'GUARD: nothing was swapped');

-- the remedy: X ends, B's statement finishes, the swap goes through and the rows are whole
select is((select s from dblink_get_result('b_p1') as t(s text)), '', 'GUARD: B''s statement finished');
select dblink_exec('x_p1', 'commit');
select is(pgpm.regrain_step('public.p1a', (select v from p1_state where k = 'src'), '100'), 'swapped:5',
  'GUARD: once X has ended the same swap goes through');
select bag_eq(
  $$ select id from public.p1a $$,
  $$ select g::bigint from generate_series(26, 494, 26) g union all select 2600 $$,
  'GUARD: the table reads exactly its rows: the multiples of 26 to 494, and 2600');

select dblink_disconnect('b_p1');
select dblink_disconnect('x_p1');
select dblink_exec('dbname=' || current_database() || ' user=postgres',
                   format('drop database %I', current_database() || '_x'));
select * from finish();
