-- The regrain swap's snapshot wait, while a transaction older than the copies runs in ANOTHER database (issue #1263).
--
-- THE REPORT. _snapshot_wait lists every session of this database whose pg_stat_activity.backend_xmin is at or
-- before the copies' last write. backend_xmin is cluster-wide: while a transaction that took its xid before that
-- write stays open in another database, every snapshot taken anywhere in the cluster has an xmin at or before it,
-- so a READ COMMITTED statement of this database that began after the copies committed, and sees them whole, is
-- listed too, and the swap defers at its budget for the foreign transaction's whole life. The refusal named that
-- local pid as a reader that "would find the regrained range empty", and docs/reference.md said other databases
-- were not consulted.
--
-- WHY THE SWAP STILL WAITS. The issue asks for that statement to be passed. Nothing a caller can read tells it
-- from a snapshot that cannot see the copies: part A builds the pair. B, the issue's reader, runs a statement that
-- began after the copies. I began its transaction after the copies too, imported (SET TRANSACTION SNAPSHOT) a
-- snapshot that E exported before them, and E has since committed. Their pg_stat_activity rows agree on the
-- database, backend_xmin (both the foreign transaction's xid), backend_xid, backend_type, state and wait event, and
-- both began after the copies; yet B's statement counts every copy's log row and I's counts none. A rule that
-- passes B passes I, and I, first reading the table after the swap, would find the regrained range empty: the
-- #1241 loss. PostgreSQL's own CREATE INDEX CONCURRENTLY waits the same way (its reference xmin is cluster-wide).
-- So the wait keeps waiting, and the fix is the contract and the message.
--
-- THE CONTRACT.
--   PART A  with the foreign transaction open, a hand regrain_step refuses at its budget, and the refusal names the
--           transaction that holds every snapshot back (its database, pid and xid) and says the sessions it lists
--           cannot be told from snapshots that miss the copies, instead of calling them readers that would find
--           the range empty. B and I are both listed. Nothing swapped, and I reads exactly its rows.
--   PART B  the remedy the message types: end that transaction. Once it has committed (and I has ended), B's next
--           statement has an xmin past the copies, and the same swap goes through with B running it.
--   PART C  against the call's own transaction (regrain(), which copies and swaps in one transaction) every snapshot
--           open during the call is listed whatever else runs, so a foreign transaction explains nothing there: the
--           refusal has no holder clause and still names its reader as one that would find the range empty.
--
-- This file holds a transaction open in another database across several seconds, which holds back every snapshot
-- of the cluster, so the suite runs it ALONE, after the parallel files (test.sh), never beside them.
-- Every negative is paired with its premise: the foreign transaction is older than the copies' last write, the
-- run is at the swap, and both readers' statements are running with their snapshots held when the swap is tried.
-- ASYMMETRIC FIXTURES. A holds the multiples of 26 to 494 and frontier 2600; C the multiples of 29 to 493 and
-- frontier 2900; every row check names the ids.
create extension if not exists pgtap;
create extension if not exists dblink;
set client_min_messages = warning;
select plan(27);

create temp table t333_state (k text primary key, v text);
-- the other database, made and dropped by this file
select dblink_exec('dbname=' || current_database() || ' user=postgres',
                   format('create database %I', current_database() || '_x'));

-- ============================================ PART A ============================================
create table public.t333a (id bigint generated by default as identity primary key, payload text);
insert into public.t333a (id, payload) select g, 'a' || g from generate_series(26, 494, 26) g;
call pgpm.transmute('public.t333a', 'id', 100, p_paused => false);                  -- monolith [0, 500)
insert into public.t333a (id, payload) values (2600, 'frontier');                    -- freezes the monolith
insert into t333_state select 'src', child_name from pgpm.part
 where parent_table = 'public.t333a'::regclass and attached and lo = '0';
insert into t333_state select 'src_oid', child_oid::text from pgpm.part
 where parent_table = 'public.t333a'::regclass and attached and lo = '0';

-- X: a transaction in the other database, its xid taken before any copy
select dblink_connect('x333', 'dbname=' || current_database() || '_x user=postgres');
select dblink_exec('x333', 'begin');
insert into t333_state select 'xxid', x from dblink('x333', 'select pg_current_xact_id()::text') as t(x text);
insert into t333_state select 'xpid', p::text from dblink('x333', 'select pg_backend_pid()') as t(p int);
-- E: REPEATABLE READ in this database, its snapshot taken before any copy and exported; no lock on the table
select dblink_connect('e333', 'dbname=' || current_database() || ' user=postgres');
select dblink_exec('e333', 'begin isolation level repeatable read');
insert into t333_state select 'snap', s from dblink('e333', 'select pg_export_snapshot()') as t(s text);

-- the copies, one regrain_step per transaction, up to the swap's doorstep (the cursor at hi)
do $$
begin
  for i in 1..40 loop
    exit when (select regrain_cursor from pgpm.config where parent_table = 'public.t333a'::regclass) = '500';
    perform pgpm.regrain_step('public.t333a', (select v from t333_state where k = 'src'), '100');
    commit;
  end loop;
end $$;
select is((select regrain_cursor from pgpm.config where parent_table = 'public.t333a'::regclass), '500',
  'LIVENESS: (A) every sub-range is copied and the run is at the swap');
select bag_eq(
  $$ select lo::bigint from pgpm.log where parent_table = 'public.t333a'::regclass and action = 'regrain_copy' $$,
  $$ values (0::bigint), (100), (200), (300), (400) $$,
  'LIVENESS: (A) the copies ran, one batch for each of the five sub-ranges of [0, 500)');
select ok((select (select v from t333_state where k = 'xxid')::xid8 < c.regrain_written_xid
             from pgpm.config c where c.parent_table = 'public.t333a'::regclass),
  'LIVENESS: (A) the other database''s transaction X took its xid before the copies'' last write');

-- I: begins after the copies, imports E's snapshot; then E commits
select dblink_connect('i333', 'dbname=' || current_database() || ' user=postgres');
select dblink_exec('i333', 'begin isolation level repeatable read');
select dblink_exec('i333', format('set transaction snapshot %L', (select v from t333_state where k = 'snap')));
insert into t333_state select 'ipid', p::text from dblink('i333', 'select pg_backend_pid()') as t(p int);
select dblink_exec('e333', 'commit');
-- B: the issue's reader, READ COMMITTED, its statement started after the copies
select dblink_connect('b333', 'dbname=' || current_database() || ' user=postgres');
insert into t333_state select 'bpid', p::text from dblink('b333', 'select pg_backend_pid()') as t(p int);
-- the same statement in both: what its snapshot sees of the copies' log rows, then a sleep that holds it
select dblink_send_query(c, $q$select (select count(*) from pgpm.log where parent_table = 'public.t333a'::regclass
                                       and action = 'regrain_copy'), pg_sleep(4)$q$)
  from (values ('b333'), ('i333')) v(c);
do $$
begin
  for i in 1..500 loop
    perform pg_stat_clear_snapshot();
    exit when (select count(*) from pg_stat_activity
                where pid in (select v::int from t333_state where k in ('bpid', 'ipid'))
                  and state = 'active' and wait_event = 'PgSleep' and backend_xmin is not null) = 2;
    perform pg_sleep(0.01);
  end loop;
end $$;
create temp table t333_seen as
  select a.pid, a.datid, a.backend_xmin, a.backend_xid, a.backend_type, a.state, a.wait_event, a.xact_start, a.query_start
    from pg_stat_activity a where a.pid in (select v::int from t333_state where k in ('bpid', 'ipid'));
select is((select count(*) from t333_seen where state = 'active' and wait_event = 'PgSleep'), 2::bigint,
  'LIVENESS: (A) B and I are both running their statement when the swap is tried');
select ok((select bool_and(s.xact_start > l.at and s.query_start > l.at)
             from t333_seen s,
                  (select max(at) as at from pgpm.log where parent_table = 'public.t333a'::regclass and action = 'regrain_copy') l),
  'LIVENESS: (A) B''s and I''s transactions and statements all began after the last copy was logged');
select ok((select b.datid = i.datid and b.backend_xmin = i.backend_xmin and b.backend_xid is null and i.backend_xid is null
                  and b.backend_type = i.backend_type and b.state = i.state and b.wait_event = i.wait_event
             from t333_seen b, t333_seen i
            where b.pid = (select v::int from t333_state where k = 'bpid') and i.pid = (select v::int from t333_state where k = 'ipid')),
  'LIVENESS: (A) B and I agree on every column a caller judges a session by: database, backend_xmin, backend_xid, type, state, wait event');
select is((select backend_xmin::text from t333_seen where pid = (select v::int from t333_state where k = 'bpid')),
  (select v from t333_state where k = 'xxid'),
  'LIVENESS: (A) and that backend_xmin is X''s xid: the other database''s transaction holds every snapshot back');

set lock_timeout = '300ms';
select throws_like(
  format($$ select pgpm.regrain_step('public.t333a', %L, '100') $$, (select v from t333_state where k = 'src')),
  'pg_partition_magician: regrain swap deferred: 2 snapshot(s) older than the copies still open (oldest: pid '
    || least((select v::int from t333_state where k = 'bpid'), (select v::int from t333_state where k = 'ipid'))
    || ', open %; pids %); a transaction older than the copies is still running in database '
    || current_database() || '_x (pid ' || (select v from t333_state where k = 'xpid')
    || ', xid ' || (select v from t333_state where k = 'xxid')
    || ', open %): while it runs every snapshot of the cluster has an xmin at or before it, so these cannot be told from snapshots that miss the copies%',
  '(A) the refusal names the transaction holding every snapshot back, by database, pid and xid');
select throws_like(
  format($$ select pgpm.regrain_step('public.t333a', %L, '100') $$, (select v from t333_state where k = 'src')),
  '%pids ' || least((select v::int from t333_state where k = 'bpid'), (select v::int from t333_state where k = 'ipid'))
    || ', ' || greatest((select v::int from t333_state where k = 'bpid'), (select v::int from t333_state where k = 'ipid')) || ')%',
  '(A) and lists both B and I, the one that sees the copies and the one that does not');
reset lock_timeout;
select is((select count(*) from pgpm.log where parent_table = 'public.t333a'::regclass and action = 'regrain'), 0::bigint,
  '(A) nothing was swapped');
select is((select child_oid::text from pgpm.part where parent_table = 'public.t333a'::regclass and attached and lo = '0'),
  (select v from t333_state where k = 'src_oid'), '(A) the same source is still attached, by oid');

-- what each statement's snapshot saw: B every copy, I none, though nothing above told them apart
select is((select n from dblink_get_result('b333') as t(n bigint, s text)), 5::bigint,
  '(A) B''s statement saw all five copies'' log rows: its snapshot sees the copies');
select is((select n from dblink_get_result('b333') as t(n bigint, s text)), null::bigint, 'B''s result is drained');
select is((select n from dblink_get_result('i333') as t(n bigint, s text)), 0::bigint,
  '(A) I''s statement saw none of them: its snapshot cannot see the copies');
select is((select n from dblink_get_result('i333') as t(n bigint, s text)), null::bigint, 'I''s result is drained');
select bag_eq(
  $$ select id from dblink('i333', 'select id from public.t333a') as t(id bigint) $$,
  $$ select g::bigint from generate_series(26, 494, 26) g union all select 2600 $$,
  '(A) I reads exactly its rows: the multiples of 26 to 494, and 2600');

-- ============================================ PART B ============================================
-- the remedy the message names: end the transaction that holds every snapshot back (and I, which cannot see the
-- copies, ends too)
select dblink_exec('i333', 'commit');
select dblink_exec('x333', 'commit');
select dblink_send_query('b333', 'select pg_sleep(3)');
do $$
begin
  for i in 1..500 loop
    perform pg_stat_clear_snapshot();
    exit when exists (select 1 from pg_stat_activity
                       where pid = (select v::int from t333_state where k = 'bpid')
                         and state = 'active' and wait_event = 'PgSleep' and backend_xmin is not null);
    perform pg_sleep(0.01);
  end loop;
end $$;
select ok((select age(a.backend_xmin) < age(c.regrain_written_xid::xid)
             from pg_stat_activity a, pgpm.config c
            where a.pid = (select v::int from t333_state where k = 'bpid') and a.state = 'active'
              and c.parent_table = 'public.t333a'::regclass),
  'LIVENESS: (B) B is running a statement again, and its backend_xmin is now past the copies'' last write');
set lock_timeout = '300ms';
select is(pgpm.regrain_step('public.t333a', (select v from t333_state where k = 'src'), '100'), 'swapped:5',
  '(B) once X has ended, the same swap goes through with B''s statement running');
reset lock_timeout;
select bag_eq(
  $$ select lo::bigint, hi::bigint from pgpm.part where parent_table = 'public.t333a'::regclass and attached and hi::bigint <= 500 $$,
  $$ values (0::bigint, 100::bigint), (100, 200), (200, 300), (300, 400), (400, 500) $$,
  '(B) the five fine children are attached in the source''s place');
select ok(not exists (select 1 from pg_class where oid = (select v::oid from t333_state where k = 'src_oid')),
  '(B) and the source is dropped');
select bag_eq(
  $$ select id from public.t333a $$,
  $$ select g::bigint from generate_series(26, 494, 26) g union all select 2600 $$,
  '(B) a fresh read after the swap holds exactly the same rows');
select is((select s from dblink_get_result('b333') as t(s text)), '', '(B) B''s statement finished');
select is((select s from dblink_get_result('b333') as t(s text)), null, 'B''s result is drained');

-- ============================================ PART C ============================================
create table public.t333c (id bigint generated by default as identity primary key, payload text);
insert into public.t333c (id, payload) select g, 'c' || g from generate_series(29, 493, 29) g;
call pgpm.transmute('public.t333c', 'id', 100, p_paused => false);                  -- monolith [0, 500)
insert into public.t333c (id, payload) values (2900, 'frontier');
insert into t333_state select 'csrc', child_name from pgpm.part
 where parent_table = 'public.t333c'::regclass and attached and lo = '0';
select dblink_exec('x333', 'begin');
select is((select count(*) from dblink('x333', 'select pg_current_xact_id()') as t(x xid8)), 1::bigint,
  'LIVENESS: (C) a transaction with an xid is open in the other database again');
select dblink_connect('r333', 'dbname=' || current_database() || ' user=postgres');
select dblink_exec('r333', 'begin isolation level repeatable read');
insert into t333_state select 'rpid', p::text from dblink('r333', 'select pg_backend_pid() from pgpm.config limit 1') as t(p int);
set lock_timeout = '300ms';
select throws_like(
  format($$ select pgpm.regrain('public.t333c', %L, '100') $$, (select v from t333_state where k = 'csrc')),
  'pg_partition_magician: regrain swap deferred: 1 snapshot(s) older than the copies still open (oldest: pid '
    || (select v from t333_state where k = 'rpid') || ', open %; pids ' || (select v from t333_state where k = 'rpid')
    || '); a reader in one would find the regrained range empty after the swap.%',
  '(C) regrain() against its own transaction names its reader as one that would read the range empty, with no holder clause');
reset lock_timeout;
select dblink_exec('r333', 'commit');
select dblink_exec('x333', 'commit');
select is(pgpm.regrain('public.t333c', (select v from t333_state where k = 'csrc'), '100'), 5,
  'LIVENESS: (C) with the reader and X ended, regrain() splits the monolith into its five fine children');
select bag_eq(
  $$ select id from public.t333c $$,
  $$ select g::bigint from generate_series(29, 493, 29) g union all select 2900 $$,
  '(C) and the table reads exactly its rows: the multiples of 29 to 493, and 2900');

select dblink_disconnect('r333');
select dblink_disconnect('b333');
select dblink_disconnect('i333');
select dblink_disconnect('e333');
select dblink_disconnect('x333');
select dblink_exec('dbname=' || current_database() || ' user=postgres',
                   format('drop database %I', current_database() || '_x'));
select * from finish();
